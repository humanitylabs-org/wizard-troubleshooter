#!/usr/bin/env python3
"""Embed the reviewed runtime into a normal recipe; no unpublished app image required."""
import base64
import gzip
import io
from pathlib import Path
import tarfile

ROOT = Path(__file__).resolve().parents[1]
IMAGE = 'node:22-bookworm-slim@sha256:c3de60bf2f9dd0ac6370e6117950ff62d6e339527e7472301c9c78a017978392'
files = [ROOT / 'package.json', ROOT / 'server.mjs', ROOT / 'REPAIR_PROMPT.md']
files += sorted((ROOT / 'lib').glob('*.mjs'))
files += sorted(p for p in (ROOT / 'web').rglob('*') if p.is_file())
stream = io.BytesIO()
with tarfile.open(fileobj=stream, mode='w') as archive:
    for p in files:
        data = p.read_bytes()
        info = tarfile.TarInfo(str(p.relative_to(ROOT)))
        info.size, info.mode, info.mtime = len(data), 0o644, 0
        archive.addfile(info, io.BytesIO(data))
payload = base64.b64encode(gzip.compress(stream.getvalue(), mtime=0)).decode()
compose = f'''# Generated by scripts/package-app.py. No host authority; readiness remains false.
services:
  wizard-troubleshooter:
    image: {IMAGE}
    user: "1000:1000"
    read_only: true
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    pids_limit: 128
    mem_limit: 256m
    tmpfs: ["/tmp:rw,nosuid,size=64m,uid=1000,gid=1000"]
    environment:
      TROUBLESHOOT_CONTAINER: "1"
      TROUBLESHOOT_STATE: /tmp/state
      PORT: "9691"
    command:
      - sh
      - -ec
      - |
        mkdir -p /tmp/app
        printf '%s' '{payload}' | base64 -d | tar -xz -C /tmp/app
        cd /tmp/app
        exec node server.mjs
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:9691/troubleshoot/api/ping').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"]
      interval: 30s
      timeout: 5s
    x-runtipi:
      is_main: true
      internal_port: 9691
x-runtipi:
  schema_version: 2
  overrides: []
'''
(ROOT / 'runtipi/docker-compose.yml').write_text(compose)
print('Packaged', len(files), 'reviewed runtime files; readiness=false; no host mounts')
